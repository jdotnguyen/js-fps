/**
 * Where the baked character clip packs live (mocap-library spec): each in its character's folder, listed in a generated table of
 * lazy imports so that every pack stays a bundle chunk of its own.
 */

/** The generated table, relative to the project root. */
export const PACK_TABLE_PATH = 'src/data/mocap/packs.ts';

/** A character's pack, relative to the project root. */
export const packPath = (name) => `src/data/cast/${name}/mocap.json`;

/** The source of the generated table for these characters. */
export function packTable(names) {
  const loaders = [...names].sort().map((n) => `  ${JSON.stringify(n)}: () => import('../cast/${n}/mocap.json'),`);
  return (
    `// Generated by scripts/bake-mocap.mjs: one lazily loaded clip pack per character (mocap-library spec). Do not edit.\n` +
    `export const MOCAP_PACKS: Readonly<Record<string, () => Promise<{ default: unknown }>>> = {${loaders.length ? `\n${loaders.join('\n')}\n` : ''}};\n`
  );
}
